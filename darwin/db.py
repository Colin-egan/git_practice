"""Storage layer with two backends behind one tiny API:

- SQLite (default): local dev and tests. WAL, one connection, RLock.
- Postgres (DATABASE_URL set): production, e.g. Supabase behind Vercel.
  The app's sqlite-flavored SQL ('?' placeholders, cur.lastrowid) is
  adapted by PgCursor; every transaction pins search_path to the isolated
  'darwin' schema so nothing else in the database is ever touched.

DATABASE_URL may hold several comma-separated candidate DSNs (transaction
pooler, session pooler, direct host); the first that connects wins. Handy
when the reachable endpoint differs per network (serverless is usually
IPv4-only, Supabase direct hosts are IPv6).
"""

import re
import sqlite3
import threading
from contextlib import contextmanager

from . import config

_lock = threading.RLock()
_conn = None
_is_pg = False

# Tables whose INSERTs need cur.lastrowid (PgCursor adds RETURNING id).
_ID_TABLES = ("users", "agents", "bounties", "withdrawals", "ledger")

