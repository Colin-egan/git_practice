_INSERT_RE = re.compile(
    r"^\s*INSERT\s+INTO\s+(" + "|".join(_ID_TABLES) + r")\b", re.IGNORECASE
)


class PgCursor:
    """Adapts a psycopg cursor to the sqlite-flavored calls the app makes:
    '?' placeholders and .lastrowid after INSERT."""

    def __init__(self, cur):
        self._cur = cur
        self.lastrowid = None

    def execute(self, sql, params=()):
        sql = sql.replace("?", "%s")
        if _INSERT_RE.match(sql) and "RETURNING" not in sql.upper():
            self._cur.execute(sql + " RETURNING id", params)
            row = self._cur.fetchone()
            self.lastrowid = row["id"] if row else None
        else:
            self._cur.execute(sql, params)
        return self

    def fetchone(self):
        return self._cur.fetchone()

    def fetchall(self):
        return self._cur.fetchall()

    @property
    def rowcount(self):
        return self._cur.rowcount

    def close(self):
        self._cur.close()


def _connect_pg():
    import psycopg
    from psycopg.rows import dict_row

    last_err = None
    for dsn in config.DATABASE_URLS:
        try:
            conn = psycopg.connect(
                dsn,
                row_factory=dict_row,
                autocommit=True,  # we issue explicit BEGIN/COMMIT ourselves
                prepare_threshold=None,  # required behind transaction poolers
                connect_timeout=10,
            )
            with conn.cursor() as c:
                c.execute("BEGIN")
                c.execute(f"SET LOCAL search_path TO {config.PG_SCHEMA_NAME}")
                c.execute(PG_SCHEMA)
                c.execute("COMMIT")
            return conn
        except Exception as e:  # try the next candidate DSN
            last_err = e
    raise last_err


def connect(path: str | None = None):
    global _conn, _is_pg
    with _lock:
        if _conn is None:
            if config.DATABASE_URLS:
                _conn = _connect_pg()
                _is_pg = True
            else:
                _conn = sqlite3.connect(
                    path or config.DB_PATH, check_same_thread=False
                )
                _conn.row_factory = sqlite3.Row
                _conn.execute("PRAGMA journal_mode=WAL")
                _conn.execute("PRAGMA foreign_keys=ON")
                _conn.executescript(SQLITE_SCHEMA)
                _is_pg = False
        return _conn


def _reset_conn():
    global _conn
    with _lock:
        if _conn is not None:
            try:
                _conn.close()
            except Exception:
                pass
        _conn = None


def reset_for_tests(path: str) -> None:
    _reset_conn()
    connect(path)


def _begin(write: bool):
    """Open a transaction, reconnecting once if a pooled/idle Postgres
    connection has gone away underneath us."""
    for attempt in (0, 1):
        conn = connect()
        try:
            if _is_pg:
                cur = PgCursor(conn.cursor())
                cur.execute("BEGIN")
                cur.execute(f"SET LOCAL search_path TO {config.PG_SCHEMA_NAME}")
            else:
                cur = conn.cursor()
                cur.execute("BEGIN IMMEDIATE" if write else "BEGIN")
            return conn, cur
        except Exception:
            if attempt == 1 or not _is_pg:
                raise
            _reset_conn()


def _finish(conn, commit: bool) -> None:
    if _is_pg:
        conn.execute("COMMIT" if commit else "ROLLBACK")
    else:
        conn.commit() if commit else conn.rollback()


@contextmanager
def tx():
    with _lock:
        conn, cur = _begin(write=True)
        try:
            yield cur
            _finish(conn, commit=True)
        except BaseException:
            _finish(conn, commit=False)
            raise
        finally:
            cur.close()


@contextmanager
def read():
    with _lock:
        conn, cur = _begin(write=False)
        try:
            yield cur
        finally:
            _finish(conn, commit=False)
            cur.close()
